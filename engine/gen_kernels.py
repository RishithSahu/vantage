"""Generates k_aarch64.h: 1x4, 2x4 and 4x4 int8 micro-kernels for the Cortex-A72 (no dot product) in AArch64 assembly.
   python gen_kernels.py
a: MR activation rows packed [kb][MR][16];  b: 4 weight rows packed [kb][4][16];  c: MR x 4 int32 sums, row stride 16 bytes.
Per 16 positions of k and per (row, weight row) pair: smull + smlal2 (16 multiply-adds into 8 int16 lanes; two products of int8 within +-127 always fit) and one sadalp (pairwise add into the int32 sums).
The A72 issues one such vector multiply or pair-add per cycle, so 3 cycles per 16 multiply-adds is the hardware ceiling for exact integer arithmetic on this chip (measured: bench/arm)."""
NL = chr(92) + "n"
def ins(s): return '"' + s + NL + '"'
def kernel(MR):
    J = "\n        "
    zero = [ins(f"movi v{16+r}.4s, #0") for r in range(MR * 4)]
    ld_a = {1: "ld1 {v0.16b}, [%[a]], #16", 2: "ld1 {v0.16b, v1.16b}, [%[a]], #32", 4: "ld1 {v0.16b, v1.16b, v2.16b, v3.16b}, [%[a]], #64"}[MR]
    body = []
    for p in range(MR * 4):
        i, j = divmod(p, 4); T = 8 + p % 8
        body += [ins(f"smull v{T}.8h, v{i}.8b, v{4+j}.8b"), ins(f"smlal2 v{T}.8h, v{i}.16b, v{4+j}.16b"), ins(f"sadalp v{16+p}.4s, v{T}.8h")]
    epi = []
    for i in range(MR):
        a = 16 + 4 * i
        epi += [ins(f"addp v0.4s, v{a}.4s, v{a+1}.4s"), ins(f"addp v1.4s, v{a+2}.4s, v{a+3}.4s"), ins("addp v0.4s, v0.4s, v1.4s"), ins("st1 {v0.4s}, [%[c]], #16")]
    clob = ", ".join(f'"v{r}"' for r in range(32))
    return f'''static inline void k{MR}x4(const int8_t *a, const int8_t *b, long kb, int32_t *c) {{
    __asm__ volatile(
        {J.join(zero)}
        "1:{NL}"
        {ins(ld_a)}
        {ins("ld1 {v4.16b, v5.16b, v6.16b, v7.16b}, [%[b]], #64")}
        {ins("prfm pldl1keep, [%[b], #448]")}
        {J.join(body)}
        {ins("subs %[n], %[n], #1")}
        {ins("b.ne 1b")}
        {J.join(epi)}
        : [a] "+r"(a), [b] "+r"(b), [n] "+r"(kb), [c] "+r"(c)
        :
        : "cc", "memory", {clob});
}}
'''
open("k_aarch64.h", "w", encoding="utf-8").write("/* GENERATED by gen_kernels.py - do not edit. */\n" + "".join(kernel(m) for m in (1, 2, 4)))
