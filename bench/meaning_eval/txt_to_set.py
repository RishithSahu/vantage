"""text | act concept [op= cond= vs= ent= c2= ref=]  ->  <name>.tsv (id, text, eight-word gold, tag) + <name>.sha256.   python bench/meaning_eval/txt_to_set.py basic_v2"""
import hashlib, os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); F = ("act", "concept", "op", "cond", "vs", "ent", "c2", "ref")
name = sys.argv[1]; rows = []
for ln in open(os.path.join(HERE, name + ".txt"), encoding="utf-8"):
    if not ln.strip() or ln.startswith("#"): continue
    q, g = [x.strip() for x in ln.rsplit("|", 1)]; w = g.split(); d = dict(zip(F, ["none"] * 8)); d["act"], d["concept"] = w[0], w[1]
    for kv in w[2:]: k, v = kv.split("=", 1); d[k] = v
    rows.append((q, " ".join(d[k] for k in F)))
out = os.path.join(HERE, name + ".tsv")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"# {name.upper()}: generated by txt_to_set.py from {name}.txt\n")
    for i, (q, g) in enumerate(rows, 1): f.write(f"Q{i:03d}\t{q}\t{g}\t{name}\n")
open(os.path.join(HERE, name + ".sha256"), "w").write(hashlib.sha256(open(out, "rb").read()).hexdigest() + "\n"); print(name, len(rows))
