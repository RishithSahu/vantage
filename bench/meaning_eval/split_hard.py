"""Split a 4-column authoring file (id | text | frame | expected behaviour) into the compact file compact_to_tsv.py reads and an expected-answers TSV.

    python bench/meaning_eval/split_hard.py bench/meaning_eval/hard_v1_src.txt hard_v1"""
import io, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
src, name = sys.argv[1], sys.argv[2]; compact = ["# generated by split_hard.py from " + os.path.basename(src) + "\n"]; expected = ["id\texpected\n"]
for line in io.open(src, encoding="utf-8"):
    line = line.rstrip("\n")
    if line.startswith("#") or not line.strip(): compact.append(line + "\n"); continue
    i, text, frame, exp = [x.strip() for x in line.split(" | ", 3)]
    compact.append(f"{i} | {text} | {frame}\n"); expected.append(f"{i}\t{exp}\n")
io.open(os.path.join(HERE, name + ".txt"), "w", encoding="utf-8", newline="\n").write("".join(compact))
io.open(os.path.join(HERE, name + "_expected.tsv"), "w", encoding="utf-8", newline="\n").write("".join(expected)); print(len(expected) - 1, "rows")
