"""Convert a compact-format question file (id | text | act concept [op=..] ...) into the TSV the evaluators read, validating every frame against the ontology.

    python bench/meaning_eval/compact_to_tsv.py bench/meaning_eval/sealed_v2.txt bench/meaning_eval/sealed_v2.tsv"""
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)

from vgpt.meaning import ontology            # noqa: E402
from vgpt.meaning.frame import Frame         # noqa: E402


def main():
    src, dst = sys.argv[1], sys.argv[2]; O = ontology.load(); out = ["# generated by compact_to_tsv.py from " + os.path.basename(src) + "\n"]; bad = 0
    for ln, line in enumerate(io.open(src, encoding="utf-8"), 1):
        line = line.strip()
        if line.startswith("#") or not line: out.append(line + "\n") if line.startswith("#") else None; continue
        i, text, spec = [x.strip() for x in line.split(" | ")]; toks = spec.split(); kw = dict(op="none", cond="none", vs="none", ent="none")
        for t in toks[2:]:
            k, v = t.split("="); kw[k] = v
        f = Frame(toks[0], toks[1], kw["op"], kw["cond"], kw["vs"], kw["ent"]); issues = O.validate(f)
        if issues: print(f"{src}:{ln}: {text!r} -> {f.to_text()} {issues}"); bad += 1
        out.append(f"{i}\t{text}\t{f.to_text()}\tsealed\n")
    if bad: sys.exit(f"{bad} invalid rows")
    io.open(dst, "w", encoding="utf-8", newline="\n").write("".join(out)); print("wrote", dst)


if __name__ == "__main__":
    main()
