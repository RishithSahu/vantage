"""Runs the five example questions of the case study PDF (verbatim wording) through the PRODUCT (vgpt.product.make_brain: the model-only route) on two vehicle histories and writes the answers verbatim to results/five_questions_model.md. For each question the report shows the capability cards the model was given, the call it wrote, the outcome and the answer. Nothing is edited by hand, a failure is shown as a failure, and no scripted reply is sent to a clarification.
    python tools_pin.py 8,9 bench/five_questions_model.py [--model PATH --n-ctx N] [--out results/five_questions_model.md]"""
import argparse, os, sqlite3, sys, time
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, HERE)
from bench.route_audit import PDF as QS
from vgpt.modelplan import Planner
from vgpt.product import make_brain

VEH = [("gen_courier_ext", 1790406000), ("gen_demo", None)]
ap = argparse.ArgumentParser(); ap.add_argument("--model", default=os.path.join(HERE, "models", "LFM2.5-1.2B-Instruct-Q4_K_M.gguf")); ap.add_argument("--n-ctx", type=int, default=6144); ap.add_argument("--out", default=os.path.join(HERE, "results", "five_questions_model.md")); a = ap.parse_args()
P = None; out = ["# The case study's five example questions, answered by the product (model-only route, verbatim)\n", f"Model `{os.path.basename(a.model)}`; time of each answer in ms (laptop, 2 pinned cores). Generated by `bench/five_questions_model.py`.\n"]
for name, now in VEH:
    path = os.path.join(HERE, "data", name + ".db"); conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    if P is None: P = Planner(conn, model_path=a.model, n_ctx=a.n_ctx)
    else: P.reload_schema(conn)
    b = make_brain(path, now=now, planner=P); out.append(f"\n## Vehicle history `{name}`\n")
    for q in QS:
        b.reset(); t = time.perf_counter(); r = b.ask(q); ms = (time.perf_counter() - t) * 1000; pr = b.last_plan_result
        out.append(f"**{q}**  ({ms:.0f} ms, outcome `{b.outcome}`)\n")
        if pr: out.append("* cards shown: " + ", ".join(pr.card_ids) + f"\n* call: `{pr.raw}`")
        out.append(f"\n```\n{(r.get('answer') or '').strip()}\n```\n")
open(a.out, "w", encoding="utf-8").write("\n".join(out)); print("written", len(QS) * len(VEH), "questions")
