"""Generates k4x4.h: the 4x4 int8 micro-kernel for the Cortex-A72 (python gen_k4x4.py)."""
NL = chr(92) + "n"
def ins(s): return '"' + s + NL + '"'
body = []
for p in range(16):
    i, j = divmod(p, 4); T = 8 + p % 8
    body += [ins(f"smull v{T}.8h, v{i}.8b, v{4+j}.8b"), ins(f"smlal2 v{T}.8h, v{i}.16b, v{4+j}.16b"), ins(f"sadalp v{16+p}.4s, v{T}.8h")]
epi = []
for i in range(4):
    a = 16 + 4 * i
    epi += [ins(f"addp v0.4s, v{a}.4s, v{a+1}.4s"), ins(f"addp v1.4s, v{a+2}.4s, v{a+3}.4s"), ins("addp v0.4s, v0.4s, v1.4s"), ins("st1 {v0.4s}, [%[c]]"), ins("add %[c], %[c], %[ldc]")]
zero = [ins(f"movi v{r}.4s, #0") for r in range(16, 32)]
J = "\n        "
clob = ", ".join(f'"v{r}"' for r in range(32))
src = f'''/* GENERATED by gen_k4x4.py - 4x4 int8 micro-kernel for the Cortex-A72 (no dot product).  a: 4 activation rows x K packed in 16-byte k-blocks ([kb][4][16]); b: the same for 4 weight rows.
 * c receives the 4x4 int32 sums (row stride ldc bytes).  Per k-block of 16: 16 x (smull + smlal2 + sadalp) = 256 multiply-adds in 48 vector instructions. */
static inline void k4x4(const int8_t *a, const int8_t *b, long kb, int32_t *c, long ldc_bytes) {{
    __asm__ volatile(
        {J.join(zero)}
        "1:{NL}"
        {ins("ld1 {v0.16b, v1.16b, v2.16b, v3.16b}, [%[a]], #64")}
        {ins("ld1 {v4.16b, v5.16b, v6.16b, v7.16b}, [%[b]], #64")}
        {ins("prfm pldl1keep, [%[b], #448]")}
        {J.join(body)}
        {ins("subs %[n], %[n], #1")}
        {ins("b.ne 1b")}
        {J.join(epi)}
        : [a] "+r"(a), [b] "+r"(b), [n] "+r"(kb), [c] "+r"(c)
        : [ldc] "r"(ldc_bytes)
        : "cc", "memory", {clob});
}}
'''
open("k4x4.h", "w", encoding="utf-8").write(src)
